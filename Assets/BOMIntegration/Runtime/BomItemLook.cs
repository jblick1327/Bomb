using Bom.Native;
using UnityEngine;

namespace Bom.Unity
{
    // Presentation only. A native item actor (pose kind 4) drawn with Darryn's item model. The model's own
    // SimpleGemsAnim is stripped by the builder; this only spins the copy in place. Position comes from the pose.
    [DisallowMultipleComponent]
    public sealed class BomItemLook : MonoBehaviour
    {
        public const uint PoseKind = 4;
        // Darryn's SimpleGemsAnim rotation speed on the item prefabs (degrees per second about Y).
        public Transform Spin;
        public float DegreesPerSecond = 85.67f;
        static readonly GameObject[] prefabs = new GameObject[6];
        static readonly bool[] loaded = new bool[6];

        // BomPose.flags bits 8-15: 1 silver, 2 gold, 3 invincibility, 4 slow, 5 speed (Darryn's type + 1).
        public static uint Kind(BomPose pose) => (pose.flags >> 8) & 0xff;

        public static string KindName(uint kind) =>
            kind switch
            {
                1 => "silver",
                2 => "gold",
                3 => "invincibility",
                4 => "slow",
                5 => "speed",
                _ => "unknown",
            };

        // Generated by BomItemPrefabBuilder into Assets/BOMIntegration/Resources; null keeps the outline fallback.
        public static GameObject Prefab(uint kind)
        {
            if (kind < 1 || kind > 5)
                return null;
            if (!loaded[kind])
            {
                loaded[kind] = true;
                prefabs[kind] = Resources.Load<GameObject>("BomItem" + kind);
                if (prefabs[kind] == null)
                    Debug.LogWarning("BOM UNITY ITEM no prefab for kind " + kind + "; drawing an outline");
            }
            return prefabs[kind];
        }

        void LateUpdate()
        {
            if (Spin != null)
                Spin.localRotation = Quaternion.Euler(0, (Time.unscaledTime * DegreesPerSecond) % 360f, 0);
        }
    }
}
